import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const scriptArgs = process.argv.slice(2);

function argValue(flag) {
  const flagIndex = scriptArgs.indexOf(flag);

  if (flagIndex === -1 || flagIndex + 1 >= scriptArgs.length) {
    throw new Error(`Missing required argument: ${flag} <path>`);
  }

  return scriptArgs[flagIndex + 1];
}

const packageDir = process.cwd();
const sourcePath = argValue("--source");
const targetPath = argValue("--target");
const packageName = JSON.parse(readFileSync(resolve(packageDir, "package.json"), "utf8")).name;

const css = execFileSync(
  "pnpm",
  ["exec", "sass", resolve(packageDir, sourcePath), "--no-source-map", "--style=compressed"],
  { cwd: packageDir, encoding: "utf8" },
).trim();

const banner = [
  "/**",
  " * @generated by scripts/generateCssText.mjs — DO NOT EDIT.",
  ` * Source: ${sourcePath}`,
  ` * Regenerate: pnpm --filter ${packageName} build:styles`,
  " */",
].join("\n");

const target = resolve(packageDir, targetPath);

writeFileSync(target, `${banner}\nexport const CSS_TEXT = ${JSON.stringify(css)};\n`);
execFileSync("pnpm", ["exec", "biome", "format", "--write", target], {
  cwd: packageDir,
  encoding: "utf8",
});
