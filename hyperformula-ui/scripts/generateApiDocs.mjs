import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";

const require = createRequire(resolve(process.cwd(), "package.json"));
const ts = require("typescript");

const scriptArgs = process.argv.slice(2);

function argValue(flag) {
  const flagIndex = scriptArgs.indexOf(flag);

  if (flagIndex === -1 || flagIndex + 1 >= scriptArgs.length) {
    throw new Error(`Missing required argument: ${flag} <path>`);
  }

  return scriptArgs[flagIndex + 1];
}

const packageDir = process.cwd();
const targetPath = argValue("--target");
const packageName = JSON.parse(readFileSync(resolve(packageDir, "package.json"), "utf8")).name;

const CATEGORY_ORDER = [
  "Builder",
  "Editor",
  "Formula Bar",
  "Grid Adapter",
  "Engine",
  "Events",
  "Highlighting",
  "Popups",
  "Theming",
  "Utilities",
];

const configPath = resolve(packageDir, "tsconfig.json");
const configFile = ts.readConfigFile(configPath, ts.sys.readFile);
const parsedConfig = ts.parseJsonConfigFileContent(configFile.config, ts.sys, dirname(configPath));
const entryPath = resolve(packageDir, "src/index.ts");
const program = ts.createProgram([entryPath], parsedConfig.options);
const checker = program.getTypeChecker();
const sourceFile = program.getSourceFile(entryPath);
const moduleSymbol = checker.getSymbolAtLocation(sourceFile);

function kindOf(symbol) {
  if (symbol.flags & ts.SymbolFlags.Class) {
    return "class";
  }

  if (symbol.flags & ts.SymbolFlags.Interface) {
    return "interface";
  }

  if (symbol.flags & ts.SymbolFlags.TypeAlias) {
    return "type";
  }

  if (symbol.flags & ts.SymbolFlags.Function) {
    return "function";
  }

  return "const";
}

const ENTRY_POINT_ORDER = ["FormulaBuilder", "IGridAdapter", "NullAdapter", "FormulaBar"];

const byCategory = new Map();
const missingDocs = [];
const examples = [];

for (const exported of checker.getExportsOfModule(moduleSymbol)) {
  const resolved =
    exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
  const doc = ts.displayPartsToString(resolved.getDocumentationComment(checker));

  if (!doc) {
    missingDocs.push(exported.getName());
    continue;
  }

  const tags = resolved.getJsDocTags(checker);
  const categoryTag = tags.find((tag) => tag.name === "category");
  const category = categoryTag ? ts.displayPartsToString(categoryTag.text).trim() : "Other";
  const summary = doc
    .replace(/\{@link\s+([^}]+?)\s*\}/g, "`$1`")
    .replace(/\s+/g, " ")
    .split(/(?<=\.)\s/)[0]
    .trim();
  const exampleTag = tags.find((tag) => tag.name === "example");
  const hasExample = exampleTag !== undefined;

  if (exampleTag) {
    examples.push({
      name: exported.getName(),
      summary,
      code: ts.displayPartsToString(exampleTag.text).trim(),
    });
  }

  if (!byCategory.has(category)) {
    byCategory.set(category, []);
  }

  byCategory
    .get(category)
    .push({ name: exported.getName(), kind: kindOf(resolved), summary, hasExample });
}

if (missingDocs.length > 0) {
  throw new Error(`Undocumented public exports: ${missingDocs.join(", ")}`);
}

const unknownCategories = [...byCategory.keys()].filter(
  (category) => !CATEGORY_ORDER.includes(category),
);

if (unknownCategories.length > 0) {
  throw new Error(`Unknown @category values: ${unknownCategories.join(", ")}`);
}

const lines = [];

lines.push(`# ${packageName} — API at a glance`);
lines.push("");
lines.push(
  "Generated by `scripts/generateApiDocs.mjs` — DO NOT EDIT.",
  `Regenerate: \`npm run docs --workspace=${packageName}\`.`,
);
lines.push("");
lines.push(
  "Minimal reference built from the JSDoc on `src/index.ts`'s public exports.",
  "Full contracts live on the declarations (IDE hover) and in `.ai/ARCHITECTURE.md`.",
  "Runnable integrations for every supported grid live in `demo/` (see `demo/README.md`).",
);
lines.push("");

if (examples.length > 0) {
  examples.sort(
    (first, second) =>
      ENTRY_POINT_ORDER.indexOf(first.name) - ENTRY_POINT_ORDER.indexOf(second.name),
  );
  lines.push("## Examples");
  lines.push("");

  for (const example of examples) {
    lines.push(`### \`${example.name}\``);
    lines.push("");
    lines.push(example.summary);
    lines.push("");
    lines.push(example.code);
    lines.push("");
  }
}

for (const category of CATEGORY_ORDER) {
  const entries = byCategory.get(category);

  if (!entries) {
    continue;
  }

  entries.sort((first, second) => first.name.localeCompare(second.name));
  lines.push(`## ${category}`);
  lines.push("");
  lines.push("| Export | Kind | Summary |");
  lines.push("|---|---|---|");

  for (const entry of entries) {
    const marker = entry.hasExample ? " ★" : "";

    lines.push(`| \`${entry.name}\`${marker} | ${entry.kind} | ${entry.summary} |`);
  }

  lines.push("");
}

lines.push("★ = primary entry point (has an `@example` on the declaration).");
lines.push("");

writeFileSync(resolve(packageDir, targetPath), lines.join("\n"));
console.warn(`Wrote ${targetPath} (${byCategory.size} categories).`);
