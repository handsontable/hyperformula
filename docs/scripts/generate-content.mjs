/**
 * Pre-build helper: regenerates the TypeDoc-driven API reference and the
 * Netlify `_redirects` file.
 *
 * What this script does:
 *   - Reads the TypeDoc output at `docs/api/` and normalizes it into the
 *     Starlight content collection at `docs/src/content/docs/api/`. The
 *     preprocessor runs here (not at request time) because TypeDoc emits
 *     files that need the link / badge / slug transforms before Starlight
 *     can render them.
 *   - Writes `public/_redirects` mapping legacy VuePress `.html` URLs to
 *     clean Starlight URLs (301), preserving inbound and SEO links. URLs
 *     are derived from the tracked content under `src/content/docs/`.
 *
 * What this script no longer does:
 *   - Guide pages, the homepage, and the 404 page are authored directly in
 *     `docs/src/content/docs/` (Starlight-native markdown) and tracked in
 *     git. They do not pass through the preprocessor.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, statSync } from 'fs';
import { resolve, dirname, relative, join } from 'path';
import { fileURLToPath } from 'url';
import { preprocessMarkdown, slugifyPath } from '../src/plugins/vuepress-preprocessor.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const docsDir = resolve(__dirname, '..');
const repoRoot = resolve(docsDir, '..');

const srcApi = resolve(repoRoot, 'docs/api');
const outGuide = resolve(docsDir, 'src/content/docs/guide');
const outApi = resolve(docsDir, 'src/content/docs/api');

/** @param {string} dir @returns {string[]} absolute paths of all .md files */
function walkMarkdown(dir) {
  const out = [];

  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);

    if (statSync(full).isDirectory()) out.push(...walkMarkdown(full));
    else if (entry.endsWith('.md')) out.push(full);
  }

  return out;
}

/**
 * Transform the TypeDoc-generated API markdown (`docs/api/`) into the content
 * collection. README.md becomes the `api` index. Falls back to a placeholder so
 * the sidebar `autogenerate` directory always exists.
 */
function generateApi() {
  rmSync(outApi, { recursive: true, force: true });
  mkdirSync(outApi, { recursive: true });

  if (!existsSync(srcApi)) {
    writeFileSync(
      join(outApi, 'index.md'),
      '---\ntitle: API Reference\n---\n\nThe API reference is generated from the TypeScript source with TypeDoc during the docs build.\n'
    );

    return 0;
  }

  const files = walkMarkdown(srcApi);

  for (const file of files) {
    let relNoExt = relative(srcApi, file).replace(/\.md$/, '').split('\\').join('/');

    relNoExt = relNoExt.replace(/(^|\/)README$/i, '$1index');

    const slugRel = slugifyPath(relNoExt);
    const slug = `api/${slugRel}`;
    const transformed = preprocessMarkdown(readFileSync(file, 'utf8'), slug);
    const dest = join(outApi, `${slugRel}.md`);

    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, transformed);
  }

  return files.length;
}

/**
 * Emit Netlify `_redirects` mapping the legacy VuePress `.html` URLs to the new
 * clean Starlight URLs (preserves inbound/SEO links). Written to `public/` so
 * Astro copies it to `dist/` for Netlify.
 *
 * Guide redirects are derived from the tracked content collection
 * (`src/content/docs/guide/`). API redirects are derived from the TypeDoc
 * source tree under `docs/api/` if present.
 */
function generateRedirects() {
  const lines = ['# Generated by scripts/generate-content.mjs — legacy VuePress .html → clean URLs'];

  if (existsSync(outGuide)) {
    for (const file of walkMarkdown(outGuide)) {
      const rel = relative(outGuide, file).replace(/\.md$/, '').split('\\').join('/');

      lines.push(`/docs/guide/${rel}.html  /docs/guide/${slugifyPath(rel)}  301`);
    }
  }

  if (existsSync(srcApi)) {
    for (const file of walkMarkdown(srcApi)) {
      const rel = relative(srcApi, file).replace(/\.md$/, '').split('\\').join('/');
      const newSlug = slugifyPath(rel).replace(/(^|\/)readme$/i, '');

      lines.push(`/docs/api/${rel}.html  ${newSlug ? `/docs/api/${newSlug}` : '/docs/api'}  301`);
    }
  }

  const dest = resolve(docsDir, 'public/_redirects');

  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, `${lines.join('\n')}\n`);

  return lines.length - 1;
}

const apiCount = generateApi();
const redirectCount = generateRedirects();

// eslint-disable-next-line no-console
console.log(
  `[generate-content] wrote ${apiCount} API page(s) and ${redirectCount} redirects`
);
